export function detectInitialLang() {
  try {
    const saved = localStorage.getItem('ddnet_lang');
    if (saved === 'tr' || saved === 'en') return saved;
  } catch {
    // Ignore storage errors
  }
  const nav = typeof navigator !== 'undefined' ? (navigator.language || '').toLowerCase() : '';
  if (nav.startsWith('en')) return 'en';
  return 'tr';
}

export function t(lang, key, params = null) {
  const dict = DICT[lang] || DICT.tr;
  let str = dict[key] ?? DICT.tr[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      str = str.replaceAll(`{${k}}`, String(v));
    }
  }
  return str;
}

export function escapeHtml(str) {
  return String(str ?? '')
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#39;');
}

export function escapeAttr(str) {
  return escapeHtml(str);
}

export function formatTime(seconds) {
  const n = Number(seconds);
  if (!Number.isFinite(n) || n < 0) return '—';
  const totalHundredths = Math.round(n * 100);
  const hundredths = totalHundredths % 100;
  const totalSeconds = Math.floor(totalHundredths / 100);
  const secs = totalSeconds % 60;
  const totalMinutes = Math.floor(totalSeconds / 60);
  const mins = totalMinutes % 60;
  const hours = Math.floor(totalMinutes / 60);

  const secPart = `${String(secs).padStart(2, '0')}.${String(hundredths).padStart(2, '0')}`;
  if (hours > 0) {
    return `${hours}:${String(mins).padStart(2, '0')}:${secPart}`;
  }
  return `${String(totalMinutes).padStart(2, '0')}:${secPart}`;
}

export function parseReleaseMs(input) {
  if (input === null || input === undefined || input === '') return 0;
  if (typeof input === 'number' && Number.isFinite(input)) {
    return input > 1e12 ? input : input * 1000;
  }
  const s = String(input).trim();
  if (!s) return 0;
  if (/^\d+(\.\d+)?$/.test(s)) {
    const num = Number(s);
    return num > 1e12 ? num : num * 1000;
  }
  // Convert "YYYY-MM-DD HH:MM" into ISO UTC for consistent cross-browser parsing
  const isoCandidate = /^\d{4}-\d{2}-\d{2} \d{2}:\d{2}(:\d{2})?$/.test(s)
    ? s.replace(' ', 'T') + (s.length === 16 ? ':00Z' : 'Z')
    : s;
  const ms = Date.parse(isoCandidate);
  return Number.isFinite(ms) ? ms : 0;
}

export function formatDate(input, lang = 'tr') {
  const ms = parseReleaseMs(input);
  if (!ms) return '—';
  try {
    return new Intl.DateTimeFormat(lang === 'tr' ? 'tr-TR' : 'en-US', {
      year: 'numeric',
      month: 'short',
      day: 'numeric',
    }).format(new Date(ms));
  } catch {
    return new Date(ms).toISOString().slice(0, 10);
  }
}

export function formatRelativeTime(unixSeconds, lang = 'tr') {
  const ms = parseReleaseMs(unixSeconds);
  if (!ms) return '—';
  const diffSec = Math.round((ms - Date.now()) / 1000);
  const abs = Math.abs(diffSec);
  const rtf =
    typeof Intl !== 'undefined' && typeof Intl.RelativeTimeFormat === 'function'
      ? new Intl.RelativeTimeFormat(lang === 'tr' ? 'tr' : 'en', { numeric: 'auto' })
      : null;

  if (abs < 60) return rtf ? rtf.format(diffSec, 'second') : `${abs}s`;
  const diffMin = Math.round(diffSec / 60);
  if (Math.abs(diffMin) < 60) return rtf ? rtf.format(diffMin, 'minute') : `${Math.abs(diffMin)}m`;
  const diffHr = Math.round(diffMin / 60);
  if (Math.abs(diffHr) < 24) return rtf ? rtf.format(diffHr, 'hour') : `${Math.abs(diffHr)}h`;
  const diffDay = Math.round(diffHr / 24);
  if (Math.abs(diffDay) < 30) return rtf ? rtf.format(diffDay, 'day') : `${Math.abs(diffDay)}d`;
  return formatDate(ms, lang);
}

export function isRecentRelease(releaseStr, days = 30) {
  const ms = parseReleaseMs(releaseStr);
  if (!ms) return false;
  const age = Date.now() - ms;
  return age >= -86400000 && age <= days * 86400000;
}
